package main

import (
	"bytes"
	"fmt"
	"github.com/lazygophers/codegen/codegen"
	"github.com/lazygophers/log"
	"github.com/lazygophers/utils/anyx"
	"os"
	"strings"
)

func GenJsEnum(pb *codegen.PbPackage) (err error) {
	var b bytes.Buffer

	b.WriteString("import { translate } from '@i18n/tran';\n")

	b.WriteString("\n")

	{
		var source, enum, options bytes.Buffer

		for _, e := range pb.Enums() {
			var isListOption bool

			// 跳过错误数据的生成
			if strings.EqualFold(e.Name, "ErrCode") {
				continue
			}

			if strings.EqualFold(e.Name, "ListOption") {
				isListOption = true
			}

			source.Reset()
			enum.Reset()
			options.Reset()

			source.WriteString("export const ")
			source.WriteString(e.FullName)
			source.WriteString(" = {\n")

			if !isListOption {
				enum.WriteString("export const ")
				enum.WriteString(e.FullName)
				enum.WriteString("Enum = {\n")
			}

			if !isListOption {
				options.WriteString("export const ")
				options.WriteString(e.FullName)
				options.WriteString("Options = [\n")
			}

			for _, field := range e.FieldList() {
				desc := strings.TrimSpace(field.Desc())
				if !isListOption && desc == "" {
					if strings.EqualFold(field.Name, "Nil") ||
						field.Value == 0 {
						continue
					}

					return fmt.Errorf("%s.%s not found desc", e.FullName, field.FieldName())
				} else if isListOption && field.Value == 0 {
					continue
				}

				source.WriteString("\t")
				source.WriteString(field.Name)
				source.WriteString(": ")
				source.WriteString("")
				source.WriteString(anyx.ToString(field.Value))
				source.WriteString(",// ")
				source.WriteString(desc)
				source.WriteString("\n")

				if !isListOption {
					enum.WriteString("\t")
					enum.WriteString("[")
					enum.WriteString(e.FullName)
					enum.WriteString(".")
					enum.WriteString(field.Name)
					enum.WriteString("]: ")
					enum.WriteString("translate('")
					enum.WriteString(desc)
					enum.WriteString("'),\n")
				}

				if !isListOption {
					options.WriteString("\t")
					options.WriteString("{label: ")
					options.WriteString("translate('")
					options.WriteString(desc)
					options.WriteString("'), value: ")
					options.WriteString(e.FullName)
					options.WriteString(".")
					options.WriteString(field.Name)
					options.WriteString("},\n")
				}
			}

			source.WriteString("};\n\n")

			if !isListOption {
				enum.WriteString("};\n\n")
			}

			if !isListOption {
				options.WriteString("];\n\n")
			}

			if source.Len() > 0 {
				_, _ = source.WriteTo(&b)
			}

			if enum.Len() > 0 {
				_, _ = enum.WriteTo(&b)
			}

			if options.Len() > 0 {
				_, _ = options.WriteTo(&b)
			}
		}
	}

	err = os.WriteFile("assets/src/utils/constant.js", b.Bytes(), 0600)
	if err != nil {
		log.Errorf("err:%v", err)
		return err
	}

	return nil
}

func GenEnum(pb *codegen.PbPackage) (err error) {
	b := log.GetBuffer()
	defer log.PutBuffer(b)

	b.WriteString("// Code generated by protoc-gen-go. DO NOT EDIT.\n\n")

	b.WriteString("package ")
	b.WriteString(pb.GoPackageName())
	b.WriteString("\n")

	gen := func(name string) (err error) {
		enum := pb.GetEnum(name)

		b.WriteString("\n")

		b.WriteString("func (m ")
		b.WriteString(enum.FullName)
		b.WriteString(") Name() string {")
		b.WriteString("\n")

		b.WriteString("\t")
		b.WriteString("switch m{")
		b.WriteString("\n")

		fieldPrefix := enum.FullName
		if fieldPrefix != enum.Name {
			fieldPrefix = strings.TrimSuffix(fieldPrefix, enum.Name)
		}

		for _, field := range enum.FieldList() {
			if field.Desc() == "" {
				if field.Value != 0 {
					log.Panicf("%s.%s not found desc", enum.FullName, field.FieldName())
				}
				continue
			}

			b.WriteString("\t")
			b.WriteString("case ")
			b.WriteString(fieldPrefix)
			b.WriteString(field.Name)
			b.WriteString(":")
			b.WriteString("\n")

			b.WriteString("\t\t")
			b.WriteString("return ")
			b.WriteString("`")
			b.WriteString(field.Desc())
			b.WriteString("`")
			b.WriteString("\n")
		}

		b.WriteString("\t")
		b.WriteString("default:")
		b.WriteString("\n")

		b.WriteString("\t\t")
		b.WriteString("return m.String()")
		b.WriteString("\n")

		b.WriteString("\t")
		b.WriteString("}")
		b.WriteString("\n")

		b.WriteString("}")
		b.WriteString("\n")

		return nil
	}

	err = gen("MqTask_Type")
	if err != nil {
		log.Errorf("err:%v", err)
		return err
	}

	err = os.WriteFile("enum.gen.go", b.Bytes(), 0600)
	if err != nil {
		log.Errorf("err:%v", err)
		return err
	}

	return nil
}
